import { settingsFingerprint } from '../settings/session-store';

export interface CachedPluginIcon { id: string; name: string; svg: string; color?: string }
export const ICON_BLOCK_START = '/* BPM generated icons: start */';
export const ICON_BLOCK_END = '/* BPM generated icons: end */';

/** One serializer for the icon writer and the configuration integrity boundary. */
export function renderIconBlock(records: readonly CachedPluginIcon[]): string {
    const rules = [...records].sort((a, b) => a.id.localeCompare(b.id)).map(({ id, ...icon }) => {
        const selector = `[data-bpm-icon="${encodeURIComponent(id)}"]`;
        return `/* icon:${encodeURIComponent(JSON.stringify({ id, ...icon }))} */\n${selector} { --bpm-plugin-icon-svg: url("data:image/svg+xml,${encodeURIComponent(icon.svg)}");${icon.color ? ` --bpm-plugin-icon-color: ${icon.color};` : ''} }`;
    }).join('\n');
    return `${ICON_BLOCK_START}\n${rules}\n${ICON_BLOCK_END}`;
}

function parseIconFile(text: string): { prefix: string; suffix: string; records: CachedPluginIcon[] } | undefined {
    const start = text.indexOf(ICON_BLOCK_START), end = text.indexOf(ICON_BLOCK_END);
    if (start < 0 || end < start || text.indexOf(ICON_BLOCK_START, start + ICON_BLOCK_START.length) >= 0
        || text.indexOf(ICON_BLOCK_END, end + ICON_BLOCK_END.length) >= 0) return;
    const records: CachedPluginIcon[] = [], ids = new Set<string>();
    const block = text.slice(start, end + ICON_BLOCK_END.length).replace(/\r\n/g, '\n');
    for (const match of block.matchAll(/\/\* icon:([^*]+) \*\//g)) {
        let value: unknown;
        try { value = JSON.parse(decodeURIComponent(match[1])); }
        catch { return; }
        if (!value || typeof value !== 'object' || Array.isArray(value)) return;
        const row = value as Record<string, unknown>;
        if (typeof row.id !== 'string' || !row.id || row.id.length > 256 || ids.has(row.id)
            || typeof row.name !== 'string' || typeof row.svg !== 'string' || row.svg.length > 100_000
            || row.color !== undefined && (typeof row.color !== 'string' || !/^#[0-9a-f]{6}$/i.test(row.color))
            || Object.keys(row).some(key => !['id', 'name', 'svg', 'color'].includes(key))) return;
        ids.add(row.id);
        records.push({ id: row.id, name: row.name, svg: row.svg,
            ...(typeof row.color === 'string' ? { color: row.color } : {}) });
    }
    // Encoded metadata alone is not proof: every CSS rule must be exactly generated by BPM.
    if (renderIconBlock(records) !== block) return;
    return { prefix: text.slice(0, start), suffix: text.slice(end + ICON_BLOCK_END.length), records };
}

/** Cache discovery may change freely; CSS outside the generated block stays byte-sensitive. */
export function compatibleIconCache(selected: string | null, current: string | null): string | undefined {
    if (selected === null || current === null) return;
    const a = parseIconFile(selected), b = parseIconFile(current);
    return a && b && a.prefix === b.prefix && a.suffix === b.suffix ? current : undefined;
}

/** Preserve remote discoveries while applying only locally changed generated records. */
export function mergeIconCache(base: string | null, selected: string | null, current: string | null): string | undefined {
    if (base === null || selected === null || current === null) return;
    const a = parseIconFile(base), b = parseIconFile(selected), c = parseIconFile(current);
    if (!a || !b || !c || a.prefix !== c.prefix || a.suffix !== c.suffix) return;
    const baseline = new Map(a.records.map(row => [row.id, row]));
    const merged = new Map(c.records.map(row => [row.id, row]));
    for (const row of b.records) {
        if (settingsFingerprint(row) !== settingsFingerprint(baseline.get(row.id))) merged.set(row.id, row);
    }
    return `${b.prefix}${renderIconBlock([...merged.values()])}${b.suffix}`;
}
